; Executable format: 32-bit PE GUI for Windows
format PE GUI 4.0
entry start

include 'win32a.inc'

; ============================================================================
; Control IDs (Buttons)
; ============================================================================
ID_BTN_SHOW  = 101
ID_BTN_HIDE  = 102
ID_BTN_EXIT  = 103
ID_STATIC    = 104

; ============================================================================
; Data section (variables and strings)
; ============================================================================
section '.data' data readable writeable
    className   db 'AwesomeClass', 0
    titleName   db 'Interface de Contrôle', 0
    staticClass db 'STATIC', 0
    buttonClass db 'BUTTON', 0

    labelText   db 'Hello Awesome', 0
    btnShowText db 'Afficher', 0
    btnHideText db 'Cacher', 0
    btnExitText db 'Quitter', 0

    ; Warning and error messages
    warnTitle   db 'Attention', 0
    warnText    db 'Vous devez d''abord cacher le message avant de quitter !', 0

    wc          WNDCLASS
    msg         MSG
    hWnd        dd 0
    hStatic     dd 0
    hBtnShow    dd 0
    hBtnHide    dd 0
    hBtnExit    dd 0
    hRedBrush   dd 0

    ; State variable: 0 = message hidden, 1 = message visible
    msgVisible  dd 0

; ============================================================================
; Executable code section
; ============================================================================
section '.code' code readable executable

start:
    ; Create a red brush for the label background
    ; COLORREF 0x000000FF = Red
    invoke  CreateSolidBrush, $000000FF
    mov     [hRedBrush], eax

    ; Register the main window class
    mov     [wc.style], 0
    mov     [wc.lpfnWndProc], WindowProc
    mov     [wc.cbClsExtra], 0
    mov     [wc.cbWndExtra], 0

    ; Get the current application instance handle
    invoke  GetModuleHandle, 0
    mov     [wc.hInstance], eax

    ; Load the default application icon
    invoke  LoadIcon, 0, IDI_APPLICATION
    mov     [wc.hIcon], eax

    ; Load the standard arrow cursor
    invoke  LoadCursor, 0, IDC_ARROW
    mov     [wc.hCursor], eax

    ; Use the standard Windows button-face color as the window background
    invoke  GetSysColorBrush, COLOR_BTNFACE
    mov     [wc.hbrBackground], eax

    ; No menu is assigned to this window
    mov     [wc.lpszMenuName], 0

    ; Assign the window class name
    mov     [wc.lpszClassName], className

    ; Register the window class with Windows
    invoke  RegisterClass, wc

    ; Create the main application window
    ; Window size: 400 x 230 pixels
    invoke  CreateWindowEx, 0, className, titleName, \
            WS_OVERLAPPED or WS_CAPTION or WS_SYSMENU or WS_VISIBLE, \
            200, 200, 400, 230, 0, 0, [wc.hInstance], 0
    mov     [hWnd], eax

    ; =========================================================================
    ; Main Windows message loop
    ; =========================================================================
msg_loop:

    ; Wait for the next message from the Windows message queue
    invoke  GetMessage, msg, 0, 0, 0

    ; GetMessage returns 0 when WM_QUIT is received
    test    eax, eax
    jz      end_loop

    ; Translate keyboard messages when necessary
    invoke  TranslateMessage, msg

    ; Send the message to the appropriate window procedure
    invoke  DispatchMessage, msg

    ; Continue processing messages
    jmp     msg_loop

end_loop:

    ; Delete the GDI brush created at program startup
    invoke  DeleteObject, [hRedBrush]

    ; Terminate the process using the WM_QUIT return value
    invoke  ExitProcess, [msg.wParam]


; ============================================================================
; Window procedure
; Handles messages sent to the main application window
; ============================================================================
proc WindowProc hwnd, umsg, wparam, lparam

    ; Check whether the main window is being created
    cmp     [umsg], WM_CREATE
    je      .wmcreate

    ; Check for commands generated by controls such as buttons
    cmp     [umsg], WM_COMMAND
    je      .wmcommand

    ; Handle the color of the STATIC text control
    cmp     [umsg], WM_CTLCOLORSTATIC
    je      .wmctlcolorstatic

    ; Handle a request to close the window
    cmp     [umsg], WM_CLOSE
    je      .wmclose

    ; Handle final window destruction
    cmp     [umsg], WM_DESTROY
    je      .wmdestroy

    ; Let Windows process all messages that are not handled here
    invoke  DefWindowProc, [hwnd], [umsg], [wparam], [lparam]
    ret


.wmcreate:

    ; -------------------------------------------------------------------------
    ; 1. Create the STATIC text control
    ; -------------------------------------------------------------------------

    ; The control is hidden when the program starts because
    ; WS_VISIBLE is intentionally not specified.
    invoke  CreateWindowEx, 0, staticClass, labelText, \
            WS_CHILD or SS_CENTER, \
            80, 20, 220, 30, [hwnd], ID_STATIC, [wc.hInstance], 0

    ; Save the handle of the STATIC control
    mov     [hStatic], eax


    ; -------------------------------------------------------------------------
    ; 2. Create the "Afficher" button
    ; -------------------------------------------------------------------------
    invoke  CreateWindowEx, 0, buttonClass, btnShowText, \
            WS_CHILD or WS_VISIBLE or BS_PUSHBUTTON, \
            30, 110, 100, 30, [hwnd], ID_BTN_SHOW, [wc.hInstance], 0

    ; Save the button handle
    mov     [hBtnShow], eax


    ; -------------------------------------------------------------------------
    ; 3. Create the "Cacher" button
    ; -------------------------------------------------------------------------
    invoke  CreateWindowEx, 0, buttonClass, btnHideText, \
            WS_CHILD or WS_VISIBLE or BS_PUSHBUTTON, \
            140, 110, 100, 30, [hwnd], ID_BTN_HIDE, [wc.hInstance], 0

    ; Save the button handle
    mov     [hBtnHide], eax


    ; -------------------------------------------------------------------------
    ; 4. Create the "Quitter" button
    ; -------------------------------------------------------------------------
    invoke  CreateWindowEx, 0, buttonClass, btnExitText, \
            WS_CHILD or WS_VISIBLE or BS_PUSHBUTTON, \
            250, 110, 100, 30, [hwnd], ID_BTN_EXIT, [wc.hInstance], 0

    ; Save the button handle
    mov     [hBtnExit], eax

    ; Return 0: WM_CREATE was processed successfully
    xor     eax, eax
    ret


.wmcommand:

    ; WM_COMMAND contains the control ID in the low-order word of WPARAM
    mov     eax, [wparam]

    ; Keep only the low-order 16 bits to extract the control ID
    and     eax, 0FFFFh

    ; Check whether the "Afficher" button was pressed
    cmp     eax, ID_BTN_SHOW
    je      .on_show

    ; Check whether the "Cacher" button was pressed
    cmp     eax, ID_BTN_HIDE
    je      .on_hide

    ; Check whether the "Quitter" button was pressed
    cmp     eax, ID_BTN_EXIT
    je      .on_exit

    ; Command was processed
    xor     eax, eax
    ret


.on_show:

    ; Show the STATIC message control
    invoke  ShowWindow, [hStatic], SW_SHOW

    ; Update the state flag: message is now visible
    mov     [msgVisible], 1

    xor     eax, eax
    ret


.on_hide:

    ; Hide the STATIC message control
    invoke  ShowWindow, [hStatic], SW_HIDE

    ; Update the state flag: message is now hidden
    mov     [msgVisible], 0

    xor     eax, eax
    ret


.on_exit:

    ; Request the main window to close.
    ; WM_CLOSE will perform the state check before allowing the exit.
    invoke  SendMessage, [hwnd], WM_CLOSE, 0, 0

    xor     eax, eax
    ret


.wmctlcolorstatic:

    ; Set STATIC control text color to blue
    invoke  SetTextColor, [wparam], $00FF0000

    ; Set STATIC control background color to red
    invoke  SetBkColor, [wparam], $000000FF

    ; Return the red brush that Windows should use
    ; to paint the STATIC control background
    mov     eax, [hRedBrush]
    ret


.wmclose:

    ; Check the current message visibility state
    ; This check applies both to the "Quitter" button
    ; and to the standard X button in the title bar.
    cmp     [msgVisible], 1
    jne     .can_close

    ; The message is still visible.
    ; Display a warning and prevent the application from closing.
    invoke  MessageBox, [hwnd], warnText, warnTitle, \
            MB_OK or MB_ICONWARNING

    ; Return 0 without destroying the window
    xor     eax, eax
    ret


.can_close:

    ; The message is hidden, so closing the application is allowed
    invoke  DestroyWindow, [hwnd]

    xor     eax, eax
    ret


.wmdestroy:

    ; Post WM_QUIT to terminate the main message loop
    invoke  PostQuitMessage, 0

    xor     eax, eax
    ret

endp


; ============================================================================
; Win32 API import section
; ============================================================================
section '.idata' import data readable

    ; Import the required Windows system libraries
    library kernel32, 'kernel32.dll', \
            user32,   'user32.dll', \
            gdi32,    'gdi32.dll'

    ; -------------------------------------------------------------------------
    ; Kernel32 API functions
    ; -------------------------------------------------------------------------
    import kernel32, \
           GetModuleHandle, 'GetModuleHandleA', \
           ExitProcess,     'ExitProcess'

    ; -------------------------------------------------------------------------
    ; User32 API functions
    ; -------------------------------------------------------------------------
    import user32, \
           RegisterClass,    'RegisterClassA', \
           CreateWindowEx,   'CreateWindowExA', \
           DefWindowProc,    'DefWindowProcA', \
           GetMessage,       'GetMessageA', \
           TranslateMessage, 'TranslateMessage', \
           DispatchMessage,  'DispatchMessageA', \
           SendMessage,      'SendMessageA', \
           ShowWindow,       'ShowWindow', \
           MessageBox,       'MessageBoxA', \
           DestroyWindow,    'DestroyWindow', \
           PostQuitMessage,  'PostQuitMessage', \
           LoadIcon,         'LoadIconA', \
           LoadCursor,       'LoadCursorA', \
           GetSysColorBrush, 'GetSysColorBrush'

    ; -------------------------------------------------------------------------
    ; GDI32 API functions
    ; -------------------------------------------------------------------------
    import gdi32, \
           CreateSolidBrush, 'CreateSolidBrush', \
           SetTextColor,     'SetTextColor', \
           SetBkColor,       'SetBkColor', \
           DeleteObject,     'DeleteObject'